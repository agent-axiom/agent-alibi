const translations: Record<Locale, TranslationMap> = { en, ru, zh };

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "ru" || value === "zh";
}

export function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "en";
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    return isLocale(stored) ? stored : "en";
  } catch {
    return "en";
  }
}

export function writeStoredLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Locale stays in React state even when storage is blocked.
  }
}

export function t(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template = translations[locale][key] ?? translations.en[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, token: string) => String(values[token] ?? `{${token}}`));
}

export function localizeText(locale: Locale, text: string | null | undefined): string {
  if (!text) return "";
  if (locale === "en") return text;
  const replacements = locale === "ru" ? ruTextReplacements : zhTextReplacements;
  return replacements.reduce((value, [pattern, replacement]) => value.replace(pattern, replacement), text);
}

